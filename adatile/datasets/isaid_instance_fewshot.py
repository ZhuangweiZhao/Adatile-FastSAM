"""
iSAID Instance Few-Shot Dataset (v3 协议) | Instance Few-Shot Dataset (v3 Protocol).
=============================================================================

基于 v3 重构方案，弃用 iSAID-5i (FSS protocol)，使用自定义 Instance Few-Shot Split。
Based on v3 restructuring, replaces iSAID-5i (FSS protocol) with custom Instance Few-Shot Split.

数据来源 | Data Source::

    ``tools/data/prep_isaid_instance.py`` 生成的 896×896 tile + COCO JSON 标注。
    Generated by tools/data/prep_isaid_instance.py → 896×896 tiles + COCO JSON annotations.

两种模式 | Two Modes::

    1. **Base Mode** — 全量 Base 类数据，用于预训练 Decoder
       Full Base class data, for pre-training the Decoder.
    2. **Novel Mode** — Novel 类 K-shot 数据，用于 Few-Shot Fine-tuning
       Novel class K-shot data, for Few-Shot Fine-tuning.

返回格式 | Return Format::

    {
        "image": Tensor[3, 896, 896],
        "instances": [
            {"mask": Tensor[H,W] bool, "category_id": int, "bbox": [x,y,w,h], "area": float},
            ...
        ],
        "tile_id": int,
        "orig_image_id": int,
        "tile_origin": (x, y),  # tile 在全图中的坐标
    }

类别 ID 体系 | Category ID System::

    使用标准 ``adatile.utils.label_mapping.ISAID_CATEGORIES`` (1-15)。
    与 prep_isaid_instance.py 输出一致。
    Uses standard ISAID_CATEGORIES (1-15), consistent with prep_isaid_instance.py output.

用法 | Usage::

    from adatile.datasets.isaid_instance_fewshot import (
        ISAIDInstanceFewShotDataset, sample_k_shot
    )

    # Base 预训练 | Base pre-training
    ds_base = ISAIDInstanceFewShotDataset(
        root="data/iSAID_instance_fewshot", split="train", fold=0, mode="base",
    )

    # Novel K-shot fine-tune | Novel K-shot fine-tune
    ds_novel = ISAIDInstanceFewShotDataset(
        root="data/iSAID_instance_fewshot", split="train", fold=0, mode="novel",
    )
    k_shot_indices = sample_k_shot(ds_novel, k=5, seed=42)

架构演进 | Architecture Evolution::

    v2: ISAIDInstanceDataset (iSAID-5i, 256² tiles, semantic masks, FSS protocol)
    v3: ISAIDInstanceFewShotDataset (896² tiles, COCO JSON, Instance Few-Shot protocol)
"""

from __future__ import annotations

import json
import random
from collections import defaultdict
from pathlib import Path
from typing import Optional

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset


# ═══════════════════════════════════════════════════════════════════
# 常量 | Constants
# ═══════════════════════════════════════════════════════════════════

ISAID_CATEGORIES: dict[int, str] = {
    1: "small_vehicle", 2: "large_vehicle", 3: "plane",
    4: "storage_tank", 5: "ship", 6: "harbor",
    7: "ground_track_field", 8: "soccer_ball_field", 9: "tennis_court",
    10: "swimming_pool", 11: "baseball_diamond", 12: "basketball_court",
    13: "bridge", 14: "helicopter", 15: "roundabout",
}

# 3-Fold Base/Novel 划分 | 3-Fold Base/Novel split definitions
# 与 prep_isaid_instance.py 一致 | Consistent with prep_isaid_instance.py
DEFAULT_FOLDS: dict[int, dict] = {
    0: {"base": [5, 4, 11, 9, 7, 13, 2, 14, 8, 3],
        "novel": [1, 6, 10, 12, 15]},
    1: {"base": [5, 4, 11, 12, 1, 14, 10, 15, 8, 6],
        "novel": [9, 7, 13, 2, 3]},
    2: {"base": [9, 12, 7, 13, 2, 1, 10, 15, 3, 6],
        "novel": [5, 4, 11, 14, 8]},
}

IGNORE_INDEX = 255
MIN_INSTANCE_AREA = 16


# ═══════════════════════════════════════════════════════════════════
# 数据集类 | Dataset Class
# ═══════════════════════════════════════════════════════════════════

class ISAIDInstanceFewShotDataset(Dataset):
    """
    iSAID Instance Few-Shot Dataset (v3 协议) | v3 Protocol Dataset.

    基于 896×896 tile + COCO JSON 标注的实例分割数据集。
    支持 Base/Novel 分划 + K-shot 采样。
    Instance segmentation dataset based on 896×896 tiles + COCO JSON annotations.
    Supports Base/Novel split + K-shot sampling.

    Parameters
    ----------
    root : str
        数据根目录 | Data root directory (data/iSAID_instance_fewshot/).
    split : str
        "train" 或 "val".
    fold : int
        Fold ID (0/1/2). 决定 Base/Novel 类别划分.
    mode : str
        "base": 只加载 Base 类数据 (预训练用) | Load Base class data only (for pre-training).
        "novel": 只加载 Novel 类数据 (Few-shot fine-tune 用) | Load Novel class data only.
        "all": 加载全部 15 类 | Load all 15 classes.
    novel_ids : list[int] | None
        手动指定 Novel 类 ID (覆盖 fold 定义) | Manually specify Novel class IDs.
    base_ids : list[int] | None
        手动指定 Base 类 ID (覆盖 fold 定义) | Manually specify Base class IDs.
    min_instances_per_tile : int
        过滤: tile 至少包含 N 个实例 | Filter: tile must have at least N instances.
    """

    def __init__(
        self,
        root: str = "data/iSAID_instance_fewshot",
        split: str = "train",
        fold: int = 0,
        mode: str = "base",
        novel_ids: list[int] | None = None,
        base_ids: list[int] | None = None,
        min_instances_per_tile: int = 0,
    ):
        self.root = Path(root)
        self.split = split
        self.fold = fold
        self.mode = mode

        # ── 验证 | Validate ──
        if mode not in ("base", "novel", "all"):
            raise ValueError(f"mode must be 'base', 'novel', or 'all', got '{mode}'")

        # ── 类别划分 | Class Split ──
        # 优先从 folds/ JSON 加载, 回退到 DEFAULT_FOLDS
        # Load from folds/ JSON first, fallback to DEFAULT_FOLDS
        fold_path = self.root / "folds" / f"fold_{fold}.json"
        if fold_path.exists():
            with open(fold_path) as f:
                fold_data = json.load(f)
            self.base_ids = set(base_ids) if base_ids else set(fold_data["base"])
            self.novel_ids = set(novel_ids) if novel_ids else set(fold_data["novel"])
        elif fold in DEFAULT_FOLDS:
            fd = DEFAULT_FOLDS[fold]
            self.base_ids = set(base_ids) if base_ids else set(fd["base"])
            self.novel_ids = set(novel_ids) if novel_ids else set(fd["novel"])
        else:
            raise ValueError(
                f"Unknown fold {fold}. Available: {list(DEFAULT_FOLDS.keys())}"
            )

        # ── 确定可见类 | Determine Visible Classes ──
        if mode == "base":
            self._visible_ids = self.base_ids
        elif mode == "novel":
            self._visible_ids = self.novel_ids
        else:  # "all"
            self._visible_ids = self.base_ids | self.novel_ids

        self.all_class_ids = sorted(self.base_ids | self.novel_ids)

        # ── 加载 COCO JSON | Load COCO JSON ──
        anno_path = self.root / "annotations" / f"instances_{split}.json"
        if not anno_path.exists():
            raise FileNotFoundError(
                f"Annotation file not found: {anno_path}\n"
                f"Run 'python tools/data/prep_isaid_instance.py' first to generate data."
            )

        with open(anno_path) as f:
            coco_data = json.load(f)

        self._tiles = coco_data.get("images", [])
        self._annotations = coco_data.get("annotations", [])
        self._categories = coco_data.get("categories", [])

        # ── 查询索引 | Query Indices ──
        # tile_id → tile info
        self._tile_by_id: dict[int, dict] = {t["id"]: t for t in self._tiles}
        # tile_id → list of annotations (按 mode 过滤) | tile_id → list of annotations (filtered by mode)
        self._ann_by_tile: dict[int, list[dict]] = defaultdict(list)
        # class_id → list of tile indices
        self._class_to_tile_indices: dict[int, list[int]] = defaultdict(list)

        self._active_tile_indices: list[int] = []
        self._build_indices(min_instances_per_tile)

        # ── 图像目录 | Image Directory ──
        self._img_dir = self.root / "images" / split

        # ── 日志 | Log ──
        n_tiles = len(self._active_tile_indices)
        n_anns = sum(
            len(self._ann_by_tile.get(self._tiles[idx]["id"], []))
            for idx in self._active_tile_indices
        )
        print(
            f"[ISAIDInstanceFewShotDataset] {split}, fold={fold}, mode={mode}: "
            f"{n_tiles} tiles, {n_anns} instances, "
            f"classes={sorted(self._visible_ids)}"
        )

    def _build_indices(self, min_instances: int) -> None:
        """
        构建 Tile 索引: 按 mode 过滤 + 建立 class→tile 映射。
        Build tile index: filter by mode + build class→tile mapping.
        """
        # 按 tile_id 分组标注 | Group annotations by tile_id
        anns_by_tile_id: dict[int, list[dict]] = defaultdict(list)
        for ann in self._annotations:
            cat_id = ann.get("category_id", 0)
            if cat_id in self._visible_ids:
                anns_by_tile_id[ann["image_id"]].append(ann)

        self._ann_by_tile = anns_by_tile_id

        # 遍历所有 tile, 过滤 + 建立 class→tile 映射
        # Iterate all tiles, filter + build class→tile mapping
        for tile_idx, tile_info in enumerate(self._tiles):
            tile_id = tile_info["id"]
            tile_anns = anns_by_tile_id.get(tile_id, [])

            if min_instances > 0 and len(tile_anns) < min_instances:
                continue

            # 即使无可见类实例, 也保留 tile (作为 BG 样本)
            # Keep tile even without visible class instances (as BG sample)
            self._active_tile_indices.append(tile_idx)
            active_idx = len(self._active_tile_indices) - 1  # dataset index space

            # Class→tile 映射 | Class→tile mapping (dataset index space)
            tile_cats = set(ann["category_id"] for ann in tile_anns)
            for cat_id in tile_cats:
                self._class_to_tile_indices[cat_id].append(active_idx)

    # ── 核心接口 | Core Interface ──

    def __len__(self) -> int:
        return len(self._active_tile_indices)

    def __getitem__(self, idx: int) -> dict:
        """
        加载 tile + per-instance 标注 | Load tile + per-instance annotations.

        :return: {
            "image": Tensor[3, H, W] float32 [0,1],
            "instances": [{"mask": Tensor[H,W] bool, "category_id": int, "bbox": list, "area": float}, ...],
            "tile_id": int,
            "orig_image_id": int,
            "tile_origin": (int, int),
        }
        """
        tile_idx = self._active_tile_indices[idx]
        tile_info = self._tiles[tile_idx]
        tile_id = tile_info["id"]

        # ── 加载图像 | Load image ──
        img_name = tile_info["file_name"]
        img_path = self._img_dir / img_name
        if not img_path.exists():
            raise FileNotFoundError(f"Tile image not found: {img_path}")

        img = cv2.imread(str(img_path), cv2.IMREAD_COLOR)
        if img is None:
            raise ValueError(f"Cannot read image: {img_path}")
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0
        img_tensor = torch.from_numpy(img).permute(2, 0, 1).float()  # [3, H, W]

        # ── 加载 per-instance 标注 | Load per-instance annotations ──
        instances = []
        H, W = tile_info["height"], tile_info["width"]

        for ann in self._ann_by_tile.get(tile_id, []):
            cat_id = ann["category_id"]
            if cat_id not in self._visible_ids:
                continue

            # 渲染 instance mask | Render instance mask
            inst_mask = self._render_annotation_mask(ann, H, W)
            area = inst_mask.sum()
            if area < MIN_INSTANCE_AREA:
                continue

            bbox = ann.get("bbox", [0, 0, 0, 0])

            instances.append({
                "mask": torch.from_numpy(inst_mask > 0.5).bool(),
                "category_id": cat_id,
                "bbox": [float(v) for v in bbox],
                "area": float(area),
            })

        return {
            "image": img_tensor,
            "instances": instances,
            "tile_id": tile_id,
            "orig_image_id": tile_info.get("orig_image_id", 0),
            "tile_origin": (tile_info.get("orig_x", 0), tile_info.get("orig_y", 0)),
        }

    @staticmethod
    def _render_annotation_mask(ann: dict, h: int, w: int) -> np.ndarray:
        """
        渲染单个 COCO 标注的二值掩码 | Render binary mask for a single COCO annotation.

        支持 polygon 和 bbox 格式。
        Supports polygon and bbox formats.

        :param ann: COCO 标注字典 | COCO annotation dict.
        :param h: 画布高度 | Canvas height.
        :param w: 画布宽度 | Canvas width.
        :return: [h, w] uint8 binary mask.
        """
        mask = np.zeros((h, w), dtype=np.uint8)

        seg = ann.get("segmentation", [])
        if seg and isinstance(seg, list):
            # Polygon 格式 | Polygon format
            if isinstance(seg[0], list):
                polys = seg
            elif isinstance(seg[0], (int, float)):
                polys = [seg]
            else:
                polys = []

            for poly in polys:
                if len(poly) < 6:
                    continue
                pts = np.array(poly, dtype=np.int32).reshape(-1, 1, 2)
                pts[:, :, 0] = np.clip(pts[:, :, 0], 0, w - 1)
                pts[:, :, 1] = np.clip(pts[:, :, 1], 0, h - 1)
                cv2.fillPoly(mask, [pts], 1)
        else:
            # 回退到 bbox | Fallback to bbox
            bbox = ann.get("bbox", [0, 0, 0, 0])
            x, y, bw, bh = [max(0, int(v)) for v in bbox]
            bw = min(bw, w - x)
            bh = min(bh, h - y)
            if bw > 0 and bh > 0:
                mask[y:y + bh, x:x + bw] = 1

        return mask

    # ── 查询接口 | Query Interface ──

    @property
    def tile_count(self) -> int:
        """Tile 总数 | Total number of active tiles."""
        return len(self._active_tile_indices)

    def class_to_tiles(self, class_id: int) -> list[int]:
        """
        获取包含指定类的所有 tile 索引 | Get all tile indices containing a given class.

        :param class_id: 类别 ID (1-15) | Class ID (1-15).
        :return: tile 索引列表 (dataset 索引空间, 可直接用于 dataset[idx]) | List of tile indices in dataset index space.
        """
        return self._class_to_tile_indices.get(class_id, [])

    def get_tile_info(self, idx: int) -> dict:
        """获取 tile 元信息 | Get tile metadata."""
        tile_idx = self._active_tile_indices[idx]
        return self._tiles[tile_idx]

    def get_visible_classes(self) -> list[int]:
        """当前 mode 下可见的类别 ID 列表 | List of visible class IDs in current mode."""
        return sorted(self._visible_ids)


