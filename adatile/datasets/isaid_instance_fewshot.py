# K-Shot 采样 | K-Shot Sampling
# ═══════════════════════════════════════════════════════════════════

def sample_k_shot(
    dataset: ISAIDInstanceFewShotDataset,
    k: int = 5,
    seed: int = 42,
    per_class: bool = True,
) -> list[int]:
    """
    从数据集中采样 K-shot tile 索引 | Sample K-shot tile indices from dataset.

    为每个可见类采样最多 K 个 tile, 取并集。
    Samples at most K tiles per visible class, takes union.

    :param dataset: ISAIDInstanceFewShotDataset (mode="novel" 推荐).
    :param k: 每类最少 tile 数 | Minimum tiles per class.
    :param seed: 随机种子 | Random seed.
    :param per_class: True → 每类独立采样; False → 全局随机采样.
    :return: 被选中的 tile 索引列表 | Selected tile index list (in dataset index space).
    """
    rng = random.Random(seed)
    selected: set[int] = set()

    if per_class:
        visible = dataset.get_visible_classes()
        for cls_id in sorted(visible):
            candidates = dataset.class_to_tiles(cls_id)
            if not candidates:
                print(f"  [WARNING] Class {cls_id} ({ISAID_CATEGORIES.get(cls_id, '?')}): "
                      f"0 tiles available!")
                continue
            n_pick = min(k, len(candidates))
            picked = rng.sample(candidates, n_pick)
            selected.update(picked)
    else:
        # 全局随机采样 | Global random sampling
        n_total = len(dataset)
        n_pick = min(k * len(dataset.get_visible_classes()), n_total)
        selected = set(rng.sample(range(n_total), n_pick))

    result = sorted(selected)
    n_classes = len(dataset.get_visible_classes())
    print(f"[sample_k_shot] k={k}, seed={seed}: "
          f"selected {len(result)} tiles across {n_classes} classes")
    return result


